// Copies the front-end libraries from node_modules into resources/vendor
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const vendorDir = path.join(root, 'resources', 'vendor');
const githubCssDir = path.join(root, 'node_modules', 'github-markdown-css');

const files = [
  'node_modules/marked/lib/marked.umd.js',
  'node_modules/dompurify/dist/purify.min.js'
];

fs.mkdirSync(vendorDir, { recursive: true });
for (const file of files) {
  fs.copyFileSync(path.join(root, file), path.join(vendorDir, path.basename(file)));
}

// GitHub Markdown styles, split in layout and colors so the colors can follow the themes:
// - github-markdown.css: the rules of the automatic variant, without its color variables
// - github-markdown-themes.css: the color variables of the GitHub themes, on <html> by
//   data-md-theme and data-scheme (dark only on screen: printing is always light)
const readCss = (name) => fs.readFileSync(path.join(githubCssDir, name), 'utf8').replace(/\r\n/g, '\n');
const autoCss = readCss('github-markdown.css');

// The variable blocks of the automatic variant, inside @media (prefers-color-scheme: ...) { ... { ... } }
function schemeBlock(scheme) {
  const start = autoCss.indexOf(`@media (prefers-color-scheme: ${scheme})`);
  const end = autoCss.indexOf('\n}\n', start) + 3;
  const body = autoCss.slice(start, end);
  const vars = Object.fromEntries([...body.matchAll(/^\s*(--[\w-]+):\s*([^;]+);/gm)].map((m) => [m[1], m[2]]));
  return { start, end, vars };
}
const dark = schemeBlock('dark');
const light = schemeBlock('light');
const layoutCss = autoCss.slice(0, Math.min(dark.start, light.start)) + autoCss.slice(Math.max(dark.end, light.end));

// The single-scheme files have the same rules with the colors written out: lined up declaration by
// declaration with the automatic variant, they give the value of each variable
const declarations = (css) => [...css.replace(/\/\*[\s\S]*?\*\//g, '').matchAll(/([\w-]+)\s*:\s*([^;{}]+);/g)]
  .map((m) => [m[1], m[2].trim()]);
const escapeRegExp = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const layoutDeclarations = declarations(layoutCss.slice(layoutCss.indexOf('\n}\n') + 3));

function deriveVars(name) {
  const css = readCss(name);
  const own = declarations(css.slice(css.indexOf('color-scheme:')).replace(/^color-scheme:[^;]*;/, ''));
  if (own.length !== layoutDeclarations.length) throw new Error(`${name}: rules differ from github-markdown.css`);
  const vars = {};
  layoutDeclarations.forEach(([property, value], i) => {
    if (own[i][0] !== property) throw new Error(`${name}: rules differ from github-markdown.css`);
    if (!value.includes('var(--')) return;
    const names = [];
    const pattern = value.split(/(var\(--[\w-]+(?:,[^()]*)?\))/).map((part) => {
      const match = /^var\((--[\w-]+)/.exec(part);
      if (!match) return escapeRegExp(part);
      names.push(match[1]);
      return '(.+?)';
    }).join('');
    const values = new RegExp(`^${pattern}$`).exec(own[i][1]);
    if (!values) return;
    names.forEach((varName, k) => { if (!values[k + 1].startsWith('var(')) vars[varName] = values[k + 1]; });
  });
  return vars;
}

const block = (selector, vars) =>
  `${selector} {\n${Object.entries(vars).map(([name, value]) => `  ${name}: ${value};`).join('\n')}\n}\n`;
const screenOnly = (css) => `@media screen {\n${css.replace(/^/gm, '  ').replace(/^ +$/gm, '')}}\n`;

const themesCss = [
  '/* Generated by scripts/copy-vendor.js from github-markdown-css */\n',
  '/* GitHub: also the base of the other themes */',
  block(':root', light.vars),
  screenOnly(block(':root[data-scheme="dark"]', dark.vars)),
  '/* GitHub high contrast: light colorblind, dark high contrast */',
  block(':root[data-md-theme="github-hc"]', deriveVars('github-markdown-light-colorblind.css')),
  screenOnly(block(':root[data-md-theme="github-hc"][data-scheme="dark"]', deriveVars('github-markdown-dark-high-contrast.css')))
].join('\n');

// The first block of the layout sets --fgColor-accent on .markdown-body, over the theme colors
fs.writeFileSync(path.join(vendorDir, 'github-markdown.css'), layoutCss.replace(/^\s*--fgColor-accent:[^;]*;\n/m, ''));
fs.writeFileSync(path.join(vendorDir, 'github-markdown-themes.css'), themesCss);
